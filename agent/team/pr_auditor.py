from agent.team.base_agent import BaseAgent
from agent.ai_fix.provider_router import AIProviderRouter
from agent.models import VulFinding, FixResult, TestStatus


class PRAuditor(BaseAgent):
    """PR Auditor Agent (analogous to Sajed in reference repo).
    
    Synthesizes executive security summaries, reviewer checklists, and formal PR bodies.
    """

    def __init__(self, router: AIProviderRouter):
        super().__init__(
            name="PRAuditor",
            role="Security Compliance & Technical Documentation Lead",
            router=router,
            color="purple"
        )

    def build_pr_documentation(
        self,
        finding: VulFinding,
        fix_result: FixResult,
        reviewer_assessment: dict
    ) -> str:
        """Constructs rich Markdown PR description."""
        test_badge = "✅ PASSED"
        test_details = "All regression and unit tests passed."
        if fix_result.test_result:
            if fix_result.test_result.status == TestStatus.PASSED:
                test_badge = f"✅ PASSED ({fix_result.test_result.duration_seconds}s)"
            elif fix_result.test_result.status == TestStatus.SKIPPED:
                test_badge = "⚠️ SKIPPED (No test suite found)"
            else:
                test_badge = "❌ FAILED"
                test_details = f"```\n{fix_result.test_result.failure_details or fix_result.test_result.stderr}\n```"

        explanation = fix_result.attempts[-1].explanation if fix_result.attempts else "Security patch applied."
        reviewer_feedback = reviewer_assessment.get("feedback", "Patch meets security criteria.")

        body = f"""## 🛡️ VulScanAgent Collaborative Security Remediation

### ⚠️ Vulnerability Summary
- **Title**: `{finding.title}`
- **Finding ID**: `{finding.id}`
- **Category**: `{finding.category.value.upper()}`
- **Severity**: `{finding.severity.value}`
- **Affected File**: `{finding.file_path}` (Line {finding.line_number})
- **Rule / CVE**: `{finding.rule_id or finding.cve_id or 'N/A'}`

### 🔍 Vulnerability Description
{finding.description}

### 🛠️ Remediation Applied
**Architecture & Patch**:
{explanation}

**Senior Security Reviewer Verdict**:
{reviewer_feedback}

### 🧪 Automated Test Verification
**Status**: {test_badge}  
{test_details}

### 📋 Checklist for Human Reviewer
- [ ] Confirm intended application functionality is preserved.
- [ ] Verify no secrets or sensitive environment configs are altered.
- [ ] Approve and merge to production/main branch.

---
*Autonomous Security Patch generated by **VulScanAgent Team** (`FixArchitect` + `SecurityReviewer` + `ErrorDiagnostician` + `PRAuditor`).*
"""
        self.log_thought(f"Compiled PR audit report for {finding.id}", title="📝 PRAuditor Report")
        return body
