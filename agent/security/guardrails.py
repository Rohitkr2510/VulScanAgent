import os
import re
import logging
from pathlib import Path
from typing import List, Optional

logger = logging.getLogger("VulScanAgent.Security")


class SecurityViolationError(Exception):
    """Raised when an agent action violates runtime security guardrails."""
    pass


class AgentGuardrails:
    """Runtime security controls and authorization policies for AI Agent actions.
    
    Inspired by 'awesome-agent-security' standards (e.g. agent-airlock, invariant,
    and agentic-semgrep-rules).
    """

    SECRET_MASKS = [
        (re.compile(r"\b(AKIA[0-9A-Z]{16})\b"), "AKIA[REDACTED_AWS_KEY]"),
        (re.compile(r"\b(ghp_[a-zA-Z0-9]{36}|github_pat_[a-zA-Z0-9_]{82})\b"), "[REDACTED_GITHUB_TOKEN]"),
        (re.compile(r"\b(sk-[a-zA-Z0-9]{32,64}|sk-proj-[a-zA-Z0-9-_]{48,128})\b"), "sk-[REDACTED_API_KEY]"),
        (re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH |PGP )?PRIVATE KEY-----[\s\S]*?-----END (?:RSA |EC |OPENSSH |PGP )?PRIVATE KEY-----"), "[REDACTED_PRIVATE_KEY]"),
        (re.compile(r"""(?i)(api[_-]?key|secret[_-]?key|auth[_-]?token|password)\s*[:=]\s*["']([A-Za-z0-9+/=_\-~@!#$%^&*]{16,})["']"""), r'\1="[REDACTED_CREDENTIAL]"'),
    ]

    DANGEROUS_COMMAND_SUBSTRINGS = [
        "rm -rf /",
        ":(){ :|:& };:",
        "mkfs",
        "dd if=/dev/zero",
        "curl -s http",
        "wget -q http",
        "> /dev/sda",
    ]

    @classmethod
    def validate_safe_path(cls, repo_dir: Path, relative_path: str) -> Path:
        """
        Path Traversal Shield:
        Ensures the agent-targeted file strictly resides within the repository root.
        Rejects directory escapes ('../'), absolute paths, or symlink traversal.
        """
        try:
            base = repo_dir.resolve()
            # Normalize and combine
            clean_rel = relative_path.lstrip("/\\")
            target = (base / clean_rel).resolve()

            # Verify that base directory is an ancestor of target
            if not str(target).startswith(str(base)):
                raise SecurityViolationError(
                    f"Path Traversal Blocked: Path '{relative_path}' resolves outside repository root '{base}'."
                )

            return target
        except Exception as e:
            if isinstance(e, SecurityViolationError):
                raise
            raise SecurityViolationError(f"Path validation failed for '{relative_path}': {e}")

    @classmethod
    def sanitize_command(cls, cmd_args: List[str]) -> List[str]:
        """
        Command Sanitizer & Deny-by-Default Execution Guardrail:
        Ensures tool execution is safe, prevents shell metacharacter injection,
        and disallows dangerous utility patterns.
        """
        if not cmd_args:
            raise SecurityViolationError("Command argument list cannot be empty.")

        cmd_line = " ".join(cmd_args)
        for dangerous in cls.DANGEROUS_COMMAND_SUBSTRINGS:
            if dangerous in cmd_line:
                raise SecurityViolationError(f"Dangerous command pattern detected and blocked: '{dangerous}'")

        # Disallow raw shell chaining operators in arguments
        forbidden_tokens = [";", "&&", "||", "`", "$("]
        for arg in cmd_args:
            for token in forbidden_tokens:
                if token in arg:
                    raise SecurityViolationError(f"Shell operator token '{token}' prohibited in argument: '{arg}'")

        return cmd_args

    @classmethod
    def redact_secrets(cls, text: str) -> str:
        """
        Secret Redaction & Information Disclosure Shield:
        Strips and masks credentials, API keys, and cryptographic certificates
        before saving to disk, printing to terminal, or publishing to Pull Requests.
        """
        if not text:
            return ""

        redacted = text
        for pattern, replacement in cls.SECRET_MASKS:
            redacted = pattern.sub(replacement, redacted)

        return redacted

    @classmethod
    def validate_patch_size(cls, content: str, max_chars: int = 1_000_000) -> None:
        """
        Resource Exhaustion / Bomb Defense:
        Rejects abnormally massive files generated by hallucinated recursive loops.
        """
        if len(content) > max_chars:
            raise SecurityViolationError(
                f"Generated patch size ({len(content)} chars) exceeds maximum safety threshold ({max_chars} chars)."
            )
